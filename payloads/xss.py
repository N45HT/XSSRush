def get_payload_data(payload_key: str) -> Optional[PayloadData]:
    for category in XSSR_PAYLOADS.values():
        if payload_key in category:
            return category[payload_key]
    return None

def get_all_payloads() -> List[PayloadData]:
    seen = set()
    result = []
    for category in XSSR_PAYLOADS.values():
        for p in category.values():
            if p.payload not in seen:
                seen.add(p.payload)
                result.append(p)
    return result
