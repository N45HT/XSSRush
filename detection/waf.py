def detect_waf(
    status_code: int,
    headers: Optional[Dict[str, Any]] = None,
    body: Optional[str] = None,
) -> Optional[Dict[str, Any]]:
    headers_lower = {k.lower(): str(v).lower() for k, v in (headers or {}).items()}
    body_lower = (body or "").lower()

    if status_code == 429 or "too many requests" in body_lower or "rate limit exceeded" in body_lower:
        return {
            "name": "Rate-Limiter",
            "type": "Rate-Limit",
            "status": status_code,
            "reason": "HTTP 429 / Rate Limit Exceeded",
        }

    server_val = headers_lower.get("server", "")

    for waf_name, sig in WAF_SIGNATURES.items():
        for h in sig.get("headers", []):
            if h in headers_lower:
                return {
                    "name": waf_name,
                    "type": "WAF",
                    "status": status_code,
                    "reason": f"Header '{h}' detected",
                }

        for s in sig.get("server", []):
            if s in server_val:
                return {
                    "name": waf_name,
                    "type": "WAF",
                    "status": status_code,
                    "reason": f"Server header '{server_val}'",
                }

        for b in sig.get("body", []):
            if b in body_lower:
                return {
                    "name": waf_name,
                    "type": "WAF",
                    "status": status_code,
                    "reason": f"Signature '{b}' in body",
                }

    if status_code == 403:
        generic_blocks = ["access denied", "request blocked", "forbidden", "web application firewall", "security rule"]
        for g in generic_blocks:
            if g in body_lower:
                return {
                    "name": "Generic WAF",
                    "type": "WAF",
                    "status": status_code,
                    "reason": f"HTTP 403 with '{g}' in body",
                }

    return None

class WAFManager:
    def __init__(self, logger: Optional[Logger] = None):
        self.logger = logger
        self.detected_waf: Optional[str] = None
        self.consecutive_blocks: int = 0
        self.throttled: bool = False
        self.warned: bool = False

    async def handle_response(
        self,
        status_code: int,
        headers: Optional[Dict[str, Any]],
        body: Optional[str],
        config: Any,
    ) -> bool:
        waf_info = detect_waf(status_code, headers, body)
        if not waf_info:
            self.consecutive_blocks = 0
            return False

        self.consecutive_blocks += 1
        waf_name = waf_info["name"]

        if not self.warned or self.detected_waf != waf_name:
            self.detected_waf = waf_name
            self.warned = True
            if self.logger:
                self.logger.warning(
                    f"WAF / Rate-Limit detected [{waf_name}] ({waf_info['reason']})!"
                )

        if config and (not self.throttled or self.consecutive_blocks >= 2):
            self.throttled = True
            old_min = config.delay_min
            old_max = config.delay_max
            config.delay_min = max(config.delay_min * 2, 3000)
            config.delay_max = max(config.delay_max * 2, 6000)
            backoff_sec = min(2 + self.consecutive_blocks, 8)
            if self.logger:
                self.logger.warning(
                    f"auto-throttling active: increased delay ({old_min}-{old_max}ms -> {config.delay_min}-{config.delay_max}ms), backing off {backoff_sec}s..."
                )
            await asyncio.sleep(backoff_sec)
        elif not config and self.consecutive_blocks >= 1:
            await asyncio.sleep(2)

        return True
